#!/usr/bin/env node
/*
 * export-applet.cjs — builds the portable Phantom server applet from the live
 * haksterAi implementation, so every site we add gets the identical widget
 * (owner, 2026-11-21: "you need to get a script with exact diminions cause we
 * will be using the widget to build our infrastruccture surver etc so will add
 * to all our sites 1 by 1", "topreels etc", "rmt").
 *
 * The output is a single file, dev/applet/phantom-applet.js. It carries the
 * applet's CSS, markup and behaviour copied verbatim from Layout.astro — the
 * only substitutions are the site label and the API base — so the dimensions
 * on another site cannot drift from the ones measured here.
 *
 * Usage: node dev/applet/export-applet.cjs
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'src', 'layouts', 'Layout.astro');
const OUT = path.join(__dirname, 'phantom-applet.js');

const src = fs.readFileSync(SRC, 'utf8').split('\n');
const find = (re, from = 0) => {
  for (let i = from; i < src.length; i++) if (re.test(src[i])) return i;
  return -1;
};

// ---- CSS: the <style> that opens right after the applet <aside> ----
const asideAt = find(/<aside id="phantom-server-applet"/);
if (asideAt < 0) throw new Error('applet aside not found');
const styleOpen = find(/<style>/, asideAt);
const styleClose = find(/<\/style>/, styleOpen);
const cssRaw = src.slice(styleOpen + 1, styleClose).join('\n');
// The widget must measure the same on a site with no CSS reset. haksterAi runs
// Tailwind's preflight (border-box everywhere); on a bare page the 420px card
// grew to 450px by adding its padding and border outside the box. Pin the box
// model on the applet subtree only, so dimensions cannot depend on the host.
const css = '#phantom-server-applet,#phantom-server-applet *,#phantom-server-applet *::before,#phantom-server-applet *::after{box-sizing:border-box}\n'
  // Browsers give <button> their own font and colours. haksterAi runs Tailwind's
  // preflight, which strips that; without it the action row is 5px shorter on a
  // bare page. Put the same reset on the applet's own buttons only.
  + '#phantom-server-applet button{font:inherit;color:inherit;margin:0}\n' + cssRaw;

// ---- Markup: the whole <aside> (its <style> is injected separately) ----
const asideClose = find(/<\/aside>/, asideAt);
const markupRaw = [src[asideAt], ...src.slice(styleClose + 1, asideClose + 1)].join('\n');
const markup = markupRaw
  .replace(/HaksterAI · Powered by/g, '__PHANTOM_SITE__ · Powered by')
  .replace(/haksterai\.com/g, '__PHANTOM_HOST__');

// ---- Behaviour: the first inline script after the applet ----
const scriptOpen = find(/<script is:inline data-cfasync="false">/, asideClose);
const scriptClose = find(/<\/script>/, scriptOpen);
let body = src.slice(scriptOpen + 1, scriptClose).join('\n');

// The page build on another site is not necessarily data-hakster-build.
const buildLine = "const pageBuildNow = () => document.documentElement.dataset.haksterBuild || '';";
if (!body.includes(buildLine)) throw new Error('pageBuildNow line not found');
body = body.replace(buildLine,
  "const pageBuildNow = () => document.documentElement.dataset.haksterBuild\n"
  + "          || document.documentElement.dataset.phantomBuild || cfg.build || '';");

// Every API call goes to the configured server (same origin by default).
body = body.replace(/fetch\('\/api\//g, "fetch(apiBase + '/api/");

// Site label: the strings read "haksterai.com ..." — point them at the host
// this widget is configured for. Comment lines are left alone.
body = body.split('\n').map((line) => {
  if (/^\s*(\/\/|\*|\/\*)/.test(line)) return line;
  return line.replace(/'haksterai\.com[^'\n]*'/g, (m) => `__ph(${m})`);
}).join('\n');

// Guard against a silent double-insert when a site includes the script twice.
const guarded = "if (document.getElementById('phantom-server-applet')) return;";

const out = `/* Phantom server applet — portable build of haksterAi's widget.
 * Generated by dev/applet/export-applet.cjs from src/layouts/Layout.astro.
 * Do not edit by hand: change the haksterAi applet, then re-run the exporter.
 *
 * Add it to a site with one tag:
 *   <script src="https://haksterai.com/applet/phantom-applet.js"
 *           data-site="TopReels" data-host="topreels" data-api="https://haksterai.com" defer></script>
 *
 * data-site  the site's own name in the card footer           (required)
 * data-host  the label the status lines speak about           (defaults to data-site)
 * data-api   the PhantomIDE server that answers /api/*        (default same origin)
 * data-build the page build id, if the site does not set data-phantom-build on <html>
 */
(function () {
  'use strict';
  ${guarded}
  var script = document.currentScript;
  if (!script) {
    var all = document.querySelectorAll('script[data-site][src*="phantom-applet"]');
    script = all[all.length - 1] || null;
  }
  var data = (script && script.dataset) || {};
  var cfg = {
    site: data.site || 'This site',
    host: data.host || data.site || location.hostname,
    api: String(data.api || '').replace(/\\/+$/, ''),
    build: data.build || '',
  };
  var apiBase = cfg.api;
  var __ph = function (s) { return String(s).split('haksterai.com').join(cfg.host); };

  var style = document.createElement('style');
  style.setAttribute('data-phantom-applet', '1');
  style.textContent = ${JSON.stringify(css)};
  document.head.appendChild(style);

  var holder = document.createElement('div');
  holder.innerHTML = ${JSON.stringify(markup)}
    .replace(/__PHANTOM_SITE__/g, cfg.site)
    .replace(/__PHANTOM_HOST__/g, cfg.host);
  var node = holder.firstElementChild;
  document.body.appendChild(node);

${body}
})();
`;

fs.writeFileSync(OUT, out);
console.log('wrote', OUT, out.length, 'bytes');
